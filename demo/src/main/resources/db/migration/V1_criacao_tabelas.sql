CREATE TABLE tb_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

CREATE TABLE tentativa_quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pontuacao_final INTEGER NOT NULL,
    tempo_total_gasto INTEGER NOT NULL,
    data_finalizacao TIMESTAMP,
    usuario_id BIGINT,
    quiz_id BIGINT,

    CONSTRAINT fk_tentativa_usuario
        FOREIGN KEY (usuario_id)
            REFERENCES tb_user(id),

    CONSTRAINT fk_tentativa_quiz
        FOREIGN KEY (quiz_id)
            REFERENCES quiz(id)
);

CREATE TABLE sessao_quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sessao_quiz_quiz
        FOREIGN KEY (quiz_id)
            REFERENCES quiz(id)
);

CREATE TABLE sessao_quiz_participantes (
    sessao_quiz_id BIGINT NOT NULL,
    apelido VARCHAR(255),

    CONSTRAINT fk_participantes_sessao
        FOREIGN KEY (sessao_quiz_id)
            REFERENCES sessao_quiz(id)
);

CREATE TABLE quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255),
    descricao VARCHAR(255),
    criador_id BIGINT,
    privacidade VARCHAR(255),

    CONSTRAINT fk_quiz_criador
        FOREIGN KEY (criador_id)
            REFERENCES tb_user(id)
);

CREATE TABLE quiz_perguntas (
    quiz_id BIGINT NOT NULL,
    perguntas_id BIGINT NOT NULL,

    CONSTRAINT fk_quiz_perguntas_quiz
        FOREIGN KEY (quiz_id)
            REFERENCES quiz(id),

    CONSTRAINT fk_quiz_perguntas_pergunta
        FOREIGN KEY (perguntas_id)
            REFERENCES pergunta(id),

    CONSTRAINT uk_quiz_perguntas
        UNIQUE (perguntas_id)
);


CREATE TABLE pergunta (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          enunciado VARCHAR(255),

                          tempo_resposta INTEGER NOT NULL,

                          quiz_id BIGINT,

                          CONSTRAINT fk_pergunta_quiz
                              FOREIGN KEY (quiz_id)
                                  REFERENCES quiz(id)
);

CREATE TABLE pergunta_alternativas (
    pergunta_id BIGINT NOT NULL,
    alternativas_id BIGINT NOT NULL,

    CONSTRAINT fk_pergunta_alternativas_pergunta
        FOREIGN KEY (pergunta_id)
            REFERENCES pergunta(id),

    CONSTRAINT fk_pergunta_alternativas_alternativa
        FOREIGN KEY (alternativas_id)
            REFERENCES alternativa(id),

    CONSTRAINT uk_pergunta_alternativas
        UNIQUE (alternativas_id)
);

CREATE TABLE alternativa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(255),
    correta BOOLEAN NOT NULL
);
